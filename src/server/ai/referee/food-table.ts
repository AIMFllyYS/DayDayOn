/** 名字 → 表里的一行：完全相等优先，其次包含关系（「清蒸鲈鱼」命中「鲈鱼」） */
export function findFood(name: string): FoodRow | null {
  const n = name.trim()
  if (!n) return null
  const exact = FOOD_TABLE.find((r) => r.names.includes(n))
  if (exact) return exact
  let best: { row: FoodRow; len: number } | null = null
  for (const row of FOOD_TABLE) {
    for (const alias of row.names) {
      if ((n.includes(alias) || alias.includes(n)) && (!best || alias.length > best.len)) {
        best = { row, len: alias.length }
      }
    }
  }
  return best?.row ?? null
}
